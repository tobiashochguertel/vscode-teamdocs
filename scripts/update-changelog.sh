#!/usr/bin/env bash
# Regenerate the "## [Unreleased]" section of CHANGELOG.md with git-cliff.
#
# NOTE: CHANGELOG.md is in PATCHED_FILES — run this on a feature branch and
# capture the change via fork-genpatch, or the next upstream sync reverts it.
set -euo pipefail

FILE="${1:-CHANGELOG.md}"
git cliff --unreleased --strip all > /tmp/cliff-section.md

python3 - "$FILE" <<'PY'
import re, sys
path = sys.argv[1]
section = open('/tmp/cliff-section.md').read().strip() + '\n'
lines = open(path).read().splitlines(keepends=True)
out, i = [], 0
while i < len(lines):
    if re.match(r'^## \[Unreleased\]', lines[i], re.I):
        out.append(section + '\n')
        i += 1
        while i < len(lines) and not lines[i].startswith('## ['):
            i += 1
        continue
    out.append(lines[i])
    i += 1
open(path, 'w').write(''.join(out))
PY
echo "Updated $FILE (unreleased section regenerated by git-cliff)"
